/**
 * Resolves canonical NIS name from raw strings (e.g. locationName, canalCode, layerName, etc.)
 */
export function resolveCanonicalNis(rawText?: string): string | undefined {
  if (!rawText || typeof rawText !== 'string') return undefined;
  const lower = rawText.toLowerCase();

  for (const [key, canonical] of Object.entries(NIS_CANONICAL_KEYS)) {
    if (lower.includes(key)) {
      return canonical;
    }
  }

  // Exact match against full list of NIS
  const exact = IRRIGATORS_ASSOCIATIONS.find(ia => ia.nis.toLowerCase() === lower);
  return exact ? exact.nis : undefined;
}

/**
 * Helper to fetch IAs filtered by IMO and/or NIS name
 */
export function getIAsForContext(imo?: string, nis?: string): IrrigatorsAssociation[] {
  let filtered = IRRIGATORS_ASSOCIATIONS;

  // 1. If IMO is specified, narrow down to that IMO
  if (imo && imo !== 'All' && imo !== 'All IMOs' && !imo.toLowerCase().includes('regional office')) {
    const imoKey = imo.toLowerCase().replace(/imo|office|region|iv-b/g, '').trim();
    const imoMatches = filtered.filter(ia => ia.imo.toLowerCase().includes(imoKey));
    if (imoMatches.length > 0) {
      filtered = imoMatches;
    }
  }

  // 2. If NIS is specified, find canonical NIS or fuzzy match
  if (nis && nis !== 'All' && nis !== 'All NIS') {
    const canonicalNis = resolveCanonicalNis(nis);
    if (canonicalNis) {
      const matched = filtered.filter(ia => ia.nis === canonicalNis);
      if (matched.length > 0) return matched;
      // If filtered had IMO restriction that blocked it, check all IRRIGATORS_ASSOCIATIONS
      const globalMatched = IRRIGATORS_ASSOCIATIONS.filter(ia => ia.nis === canonicalNis);
      if (globalMatched.length > 0) return globalMatched;
    }

    const nisKey = nis.toLowerCase().replace(/river|irrigation|system|project|ris|rip|sris/g, '').trim();
    if (nisKey.length > 2) {
      const fuzzy = filtered.filter(ia => 
        ia.nis.toLowerCase().includes(nisKey) || 
        nisKey.includes(ia.nis.toLowerCase().replace(/river|irrigation|system|project|ris|rip|sris/g, '').trim())
      );
      if (fuzzy.length > 0) {
        return fuzzy;
      }
    }
  }

  return filtered;
}

